#!/usr/bin/env lua
-- arithmetic.lua — All of Lua's math operators.

local a, b = 10, 3

print("a =", a, "| b =", b)
print("a + b  =", a + b)
print("a - b  =", a - b)
print("a * b  =", a * b)
print("a / b  =", a / b)
print("a // b =", a // b)
print("a % b  =", a % b)
print("a ^ b  =", a ^ b)
print("-a     =", -a)
print("math.pi =", math.pi)
